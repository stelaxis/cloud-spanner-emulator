// Every kind of node CopySchema edits: factory-owned column types (arrays,
// protos, enums), a view, a sequence, an identity column's sequence, and a
// change stream.
const std::vector<std::string>& GoogleSqlDdl() {
  static const auto* ddl = new std::vector<std::string>{
      R"(CREATE PROTO BUNDLE (emulator.tests.common.Simple,
                              emulator.tests.common.TestEnum))",
      R"(CREATE SEQUENCE seq OPTIONS (sequence_kind = 'bit_reversed_positive'))",
      R"(CREATE TABLE t (
           id INT64 NOT NULL DEFAULT (GET_NEXT_SEQUENCE_VALUE(SEQUENCE seq)),
           ident INT64 GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE),
           s STRING(MAX),
           a ARRAY<STRING(MAX)>,
           p emulator.tests.common.Simple,
           e emulator.tests.common.TestEnum,
           ap ARRAY<emulator.tests.common.Simple>,
           u STRING(MAX) AS (UPPER(s)) STORED,
         ) PRIMARY KEY (id))",
      R"(CREATE TABLE c (
           id INT64 NOT NULL,
           k INT64 NOT NULL,
           v FLOAT64,
         ) PRIMARY KEY (id, k), INTERLEAVE IN PARENT t ON DELETE CASCADE)",
      "CREATE INDEX t_by_s ON t(s) STORING (a)",
      "CREATE VIEW v SQL SECURITY INVOKER AS SELECT t.id, t.a FROM t",
      "CREATE CHANGE STREAM cs FOR t",
      "ALTER TABLE c ADD CONSTRAINT fk FOREIGN KEY (k) REFERENCES t (id)",
  };
  return *ddl;
}

const std::vector<std::string>& PostgresDdl() {
  static const auto* ddl = new std::vector<std::string>{
      "CREATE SEQUENCE seq BIT_REVERSED_POSITIVE",
      R"(CREATE TABLE t (
           id bigint NOT NULL DEFAULT nextval('seq'),
           ident bigint GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE),
           s varchar,
           a varchar[],
           n numeric,
           PRIMARY KEY (id)))",
      "CREATE INDEX t_by_s ON t(s) INCLUDE (a)",
      "CREATE VIEW v SQL SECURITY INVOKER AS SELECT t.id, t.a FROM t",
      "CREATE CHANGE STREAM cs FOR t",
  };
  return *ddl;
}

SchemaChangeOperation Operation(database_api::DatabaseDialect dialect,
                                const std::string& proto_descriptors) {
  return SchemaChangeOperation{
      .statements = dialect == database_api::DatabaseDialect::POSTGRESQL
                        ? PostgresDdl()
                        : GoogleSqlDdl(),
      .proto_descriptor_bytes =
          dialect == database_api::DatabaseDialect::POSTGRESQL
              ? absl::string_view()
              : absl::string_view(proto_descriptors),
      .database_dialect = dialect,
  };
}

std::vector<std::string> Ddl(const Database& database) {
  absl::StatusOr<std::vector<std::string>> ddl =
      PrintDDLStatements(database.GetLatestSchema());
  EXPECT_THAT(ddl, googlesql_base::testing::IsOk());
  return ddl.value_or(std::vector<std::string>{});
}

// The IDs and PostgreSQL OIDs of every table and column, which a database
// assigns from its own counters.
std::vector<std::string> Ids(const Database& database) {
  std::vector<std::string> ids;
  for (const Table* table : database.GetLatestSchema()->tables()) {
    ids.push_back(absl::StrCat(table->Name(), "=", table->id(), "/",
                               table->postgresql_oid().value_or(0)));
    for (const Column* column : table->columns()) {
      ids.push_back(absl::StrCat(column->FullName(), "=", column->id(), "/",
                                 column->postgresql_oid().value_or(0)));
    }
  }
  return ids;
}

std::vector<int64_t> DrawSequence(const Sequence* sequence, int n) {
  std::vector<int64_t> values;
  for (int i = 0; i < n; ++i) {
    absl::StatusOr<googlesql::Value> value = sequence->GetNextSequenceValue();
    EXPECT_THAT(value, googlesql_base::testing::IsOk());
    values.push_back(value.ok() ? value->int64_value() : -1);
  }
  return values;
}

const Sequence* IdentitySequence(const Database& database) {
  const Column* column =
      database.GetLatestSchema()->FindTable("t")->FindColumn("ident");
  return static_cast<const Sequence*>(column->sequences_used().at(0));
}

