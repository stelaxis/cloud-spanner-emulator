// A database created from the cache has the schema, IDs and OIDs of one
// created from DDL, and so does the same schema change applied to each.
TEST_P(SchemaCreateCacheTest, CachedDatabaseMatchesUncached) {
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> uncached,
                       Create(operation(), /*use_cache=*/false));
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> first, Create(operation()));
  EXPECT_EQ(cache_.misses(), 1);
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> cached, Create(operation()));
  EXPECT_EQ(cache_.hits(), 1);
  EXPECT_EQ(cache_.copies(), 1);

  EXPECT_THAT(Ddl(*cached), ElementsAreArray(Ddl(*uncached)));
  EXPECT_THAT(Ids(*cached), ElementsAreArray(Ids(*uncached)));
  EXPECT_THAT(Ddl(*first), ElementsAreArray(Ddl(*uncached)));

  // New tables and columns take the next IDs and OIDs, as they would on the
  // uncached database.
  std::vector<std::string> change =
      GetParam() == database_api::DatabaseDialect::POSTGRESQL
          ? std::vector<std::string>{"ALTER TABLE t ADD COLUMN x bigint",
                                     "CREATE TABLE n (k bigint PRIMARY KEY)",
                                     "CREATE INDEX t_by_x ON t(x)",
                                     "DROP INDEX t_by_s",
                                     "ALTER SEQUENCE seq SKIP RANGE 1 1000"}
          : std::vector<std::string>{
                "ALTER TABLE t ADD COLUMN x INT64",
                "CREATE TABLE n (k INT64) PRIMARY KEY (k)",
                "CREATE INDEX t_by_x ON t(x)", "DROP INDEX t_by_s",
                "ALTER SEQUENCE seq SET OPTIONS (skip_range_min = 1, "
                "skip_range_max = 1000)"};
  for (Database* database : {uncached.get(), cached.get()}) {
    int succeeded = 0;
    absl::Time commit_timestamp;
    absl::Status backfill_status;
    GOOGLESQL_ASSERT_OK(database->UpdateSchema(
        SchemaChangeOperation{.statements = change,
                              .database_dialect = GetParam()},
        &succeeded, &commit_timestamp, &backfill_status));
    GOOGLESQL_ASSERT_OK(backfill_status);
    EXPECT_EQ(succeeded, change.size());
  }
  EXPECT_THAT(Ddl(*cached), ElementsAreArray(Ddl(*uncached)));
  EXPECT_THAT(Ids(*cached), ElementsAreArray(Ids(*uncached)));
}

// A failing request is never cached and fails as it does without the cache.
TEST_P(SchemaCreateCacheTest, FailedCreateIsNotCached) {
  SchemaChangeOperation failing = operation();
  std::vector<std::string> statements(failing.statements.begin(),
                                      failing.statements.end());
  statements.push_back("CREATE TABLE t (k INT64) PRIMARY KEY (k)");
  failing.statements = statements;

  absl::Status uncached = Create(failing, /*use_cache=*/false).status();
  ASSERT_FALSE(uncached.ok());
  for (int i = 0; i < 3; ++i) {
    absl::Status cached = Create(failing).status();
    EXPECT_EQ(cached.code(), uncached.code());
    EXPECT_EQ(cached.message(), uncached.message());
  }
  EXPECT_EQ(cache_.size(), 0);
  EXPECT_EQ(cache_.hits(), 0);
}

// Each database starts its sequences where a new database's start, and draws
// from them independently of every other database.
TEST_P(SchemaCreateCacheTest, SequencesAreIndependent) {
  constexpr int kValues = 50;
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> uncached,
                       Create(operation(), /*use_cache=*/false));
  const std::vector<int64_t> expected = DrawSequence(
      uncached->GetLatestSchema()->FindSequence("seq"), kValues);
  const std::vector<int64_t> expected_identity =
      DrawSequence(IdentitySequence(*uncached), kValues);

  constexpr int kDatabases = 8;
  std::vector<std::unique_ptr<Database>> databases;
  for (int i = 0; i < kDatabases; ++i) {
    GOOGLESQL_ASSERT_OK_AND_ASSIGN(databases.emplace_back(), Create(operation()));
  }
  EXPECT_EQ(cache_.hits(), kDatabases - 1);
  EXPECT_EQ(cache_.copies(), kDatabases - 1);
  std::vector<std::thread> threads;
  for (const std::unique_ptr<Database>& database : databases) {
    threads.emplace_back([&, db = database.get()] {
      EXPECT_EQ(DrawSequence(db->GetLatestSchema()->FindSequence("seq"),
                             kValues),
                expected);
      EXPECT_EQ(DrawSequence(IdentitySequence(*db), kValues),
                expected_identity);
    });
  }
  for (std::thread& thread : threads) thread.join();
}

// Concurrent creates of the same DDL, some missing and some hitting, all get
// the same schema, while other keys evict the entry.
TEST_P(SchemaCreateCacheTest, ConcurrentCreatesOfTheSameDdl) {
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> uncached,
                       Create(operation(), /*use_cache=*/false));
  const std::vector<std::string> expected = Ddl(*uncached);
  std::vector<std::thread> threads;
  for (int t = 0; t < 16; ++t) {
    threads.emplace_back([&, t] {
      for (int i = 0; i < 3; ++i) {
        SchemaChangeOperation op = operation();
        std::vector<std::string> statements(op.statements.begin(),
                                            op.statements.end());
        if (t % 4 == 3) {
          // A different key, to evict entries.
          statements.push_back(absl::StrCat(
              GetParam() == database_api::DatabaseDialect::POSTGRESQL
                  ? "CREATE TABLE extra (k bigint PRIMARY KEY, v"
                  : "CREATE TABLE extra (k INT64, v",
              t, i,
              GetParam() == database_api::DatabaseDialect::POSTGRESQL
                  ? " bigint)"
                  : " INT64) PRIMARY KEY (k)"));
          op.statements = statements;
        }
        absl::StatusOr<std::unique_ptr<Database>> database =
            Database::Create(&clock_, absl::StrCat("db", t, "_", i), op);
        ASSERT_THAT(database, googlesql_base::testing::IsOk());
        if (t % 4 != 3) {
          EXPECT_THAT(Ddl(**database), ElementsAreArray(expected));
          EXPECT_THAT(DrawSequence((*database)->GetLatestSchema()->FindSequence(
                                       "seq"),
                                   3),
                      Not(testing::IsEmpty()));
        }
      }
    });
  }
  for (std::thread& thread : threads) thread.join();
  EXPECT_GT(cache_.hits(), 0);
  EXPECT_EQ(cache_.copies(), cache_.hits());
  EXPECT_EQ(cache_.fallbacks(), 0);
}

// A database created from an entry keeps working after the entry is evicted
// and the database the entry came from is dropped.
TEST_P(SchemaCreateCacheTest, DatabaseOutlivesItsEntry) {
  SchemaCreateCache small(1);
  SchemaCreateCache::SetGlobalForTesting(&small);
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> source,
                       Database::Create(&clock_, "source", operation()));
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> cached,
                       Database::Create(&clock_, "db", operation()));
  EXPECT_EQ(small.hits(), 1);
  EXPECT_EQ(small.copies(), 1);
  const std::vector<std::string> expected = Ddl(*source);

  SchemaChangeOperation other = operation();
  std::vector<std::string> statements(other.statements.begin(),
                                      other.statements.end());
  statements.pop_back();
  other.statements = statements;
  GOOGLESQL_ASSERT_OK(Database::Create(&clock_, "other", other).status());
  EXPECT_EQ(small.size(), 1);
  source.reset();

  EXPECT_THAT(Ddl(*cached), ElementsAreArray(expected));
  EXPECT_THAT(DrawSequence(cached->GetLatestSchema()->FindSequence("seq"), 3),
              Not(testing::IsEmpty()));
  int succeeded = 0;
  absl::Time commit_timestamp;
  absl::Status backfill_status;
  GOOGLESQL_ASSERT_OK(cached->UpdateSchema(
      SchemaChangeOperation{
          .statements = {GetParam() == database_api::DatabaseDialect::POSTGRESQL
                             ? "ALTER TABLE t ADD COLUMN x varchar[]"
                             : "ALTER TABLE t ADD COLUMN x ARRAY<INT64>"},
          .database_dialect = GetParam()},
      &succeeded, &commit_timestamp, &backfill_status));
  EXPECT_EQ(succeeded, 1);

  // The same request misses now, and creates from DDL.
  GOOGLESQL_ASSERT_OK_AND_ASSIGN(std::unique_ptr<Database> again,
                       Database::Create(&clock_, "db", operation()));
  EXPECT_EQ(small.hits(), 1);
  EXPECT_EQ(small.copies(), 1);
  EXPECT_THAT(Ddl(*again), ElementsAreArray(expected));
  SchemaCreateCache::SetGlobalForTesting(&cache_);
}

